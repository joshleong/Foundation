#!/usr/bin/env node
/**
 * Build Foundation for Chrome.
 *
 *   npm run build -w @foundation/extension      dev: dist/unpacked (Load unpacked), for FOUNDATION_URL (default http://localhost:1430)
 *   npm run release -w @foundation/extension    the official package: dist/foundation-today-<version>.zip for the Chrome Web Store,
 *                                               the store icon, and dist/policy/ (force-install and the address, for the admin)
 *
 * The release reads release.json (the hosted address, the company's domains,
 * the store id…) and lists every value still marked placeholder, so the
 * package can be made and tried before those answers are in.
 *
 * - the pages from src/, with the company's Foundation address baked in as the default;
 * - Foundation's tokens.css and its font (the same design language as the app);
 * - the company's apps from @foundation/protocol (COMPANY_APPS), as the popup's fallback shelf;
 * - icons drawn here (the Shiba's ring on paper), so there's no binary to keep in step.
 */
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { execFileSync } from "node:child_process";
import { deflateSync } from "node:zlib";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const dist = process.env.EXTENSION_DIST ? resolve(process.env.EXTENSION_DIST) : join(here, "dist");
const out = join(dist, "unpacked");
const release = process.argv.includes("--release");
const cfg0 = JSON.parse(readFileSync(join(here, "release.json"), "utf8"));
const conf = (k) => cfg0[k]?.value;
const placeholders = Object.entries(cfg0).filter(([, v]) => v && typeof v === "object" && v.placeholder).map(([k, v]) => ({ key: k, value: v.value, what: v.what }));
const url = (process.env.FOUNDATION_URL || (release ? conf("foundationUrl") : "") || "http://localhost:1430").replace(/\/+$/, "");
if (!/^https?:\/\//.test(url)) throw new Error(`FOUNDATION_URL must be http(s): ${url}`);
const version = JSON.parse(readFileSync(join(here, "package.json"), "utf8")).version;

rmSync(dist, { recursive: true, force: true });
mkdirSync(join(out, "icons"), { recursive: true });
mkdirSync(join(out, "fonts"), { recursive: true });
cpSync(join(here, "src"), out, { recursive: true });

// the address
const cfgFile = join(out, "config.js");
writeFileSync(cfgFile, readFileSync(cfgFile, "utf8").replace("__FOUNDATION_URL__", url));

// the design language: tokens + Hanken Grotesk, local (extension pages can't load the app's bundle)
const font = join(root, "node_modules/@fontsource-variable/hanken-grotesk/files/hanken-grotesk-latin-wght-normal.woff2");
cpSync(font, join(out, "fonts/hanken-grotesk.woff2"));
const tokens = readFileSync(join(root, "packages/ui/src/tokens.css"), "utf8").replace(
  /@import "@fontsource-variable\/hanken-grotesk\/index\.css";/,
  `@font-face {\n  font-family: "Hanken Grotesk Variable";\n  font-style: normal;\n  font-display: swap;\n  font-weight: 100 900;\n  src: url(fonts/hanken-grotesk.woff2) format("woff2-variations");\n}`,
);
if (tokens.includes("@import")) throw new Error("tokens.css gained an @import the extension can't follow");
writeFileSync(join(out, "tokens.css"), tokens);

// the company's apps: one list (packages/protocol/src/apps.ts), addresses unknown here
// (imported by file URL: on Windows a bare "C:\…" path is refused as a URL scheme)
const { COMPANY_APPS } = await import(pathToFileURL(join(root, "packages/protocol/src/apps.ts")).href);
const apps = COMPANY_APPS.map((a) => ({ id: a.id, name: a.name, role: a.role, glyph: a.glyph, url: a.id === "foundation" ? `${url}/#/board` : null }));
writeFileSync(join(out, "apps.js"), `// generated by build.mjs from @foundation/protocol COMPANY_APPS\nexport const FALLBACK_APPS = ${JSON.stringify(apps, null, 2)};\n`);

// icons: an agent-violet ring on paper (the Shiba's mark in Today's top bar)
for (const size of [16, 32, 48, 128]) writeFileSync(join(out, `icons/${size}.png`), icon(size));

const manifest = JSON.parse(readFileSync(join(out, "manifest.json"), "utf8"));
manifest.version = version;
const origin = new URL(url);
if (release) {
  // the official package: no localhost; Foundation's own origin and the company's domains are granted at install,
  // so an admin can move Foundation within them by policy and the popup still reads Today
  const hosts = [`${origin.origin}/*`, ...(conf("companyDomains") ?? []).map((d) => `https://*.${d}/*`)];
  manifest.host_permissions = [...new Set(hosts)];
  manifest.optional_host_permissions = ["https://*/*"];
  manifest.homepage_url = url;
} else if (!/^(localhost|127\.0\.0\.1)$/.test(origin.hostname)) {
  // a hosted Foundation is granted at install, so the popup can read Today without asking
  manifest.host_permissions.push(`${origin.origin}/*`);
}
writeFileSync(join(out, "manifest.json"), JSON.stringify(manifest, null, 2));

const zip = join(dist, release ? `foundation-today-${version}.zip` : "foundation-today.zip");
rmSync(zip, { force: true });
if (process.platform === "win32") {
  // Windows has no zip; its own bsdtar (System32, not Git's GNU tar) writes one, by the name's suffix
  execFileSync(join(process.env.SystemRoot ?? "C:\\Windows", "System32", "tar.exe"), ["-a", "-cf", zip, "."], { cwd: out });
} else {
  execFileSync("zip", ["-qr", zip, "."], { cwd: out });
}

if (release) {
  // the listing's icon: 96 px of artwork in a 128 px square (the Web Store's guidance)
  mkdirSync(join(dist, "store"), { recursive: true });
  writeFileSync(join(dist, "store/icon-128.png"), icon(128, 16));
  writePolicies(conf("extensionId") || "EXTENSION_ID", url);
}

console.log(`Foundation for Chrome ${version}${release ? " (release)" : ""} → ${out}\n  zip: ${zip}\n  Foundation: ${url}`);
if (release) {
  console.log(`  policies: ${join(dist, "policy")}`);
  if (placeholders.length) {
    console.log(`\n  ${placeholders.length} value(s) in release.json are still placeholders:`);
    for (const p of placeholders) console.log(`  - ${p.key}: ${JSON.stringify(p.value)}\n      ${p.what}`);
  }
}

/**
 * What an admin pastes, for the extension installed on everyone's Chrome with
 * Foundation's address set: the Google Admin console's policy JSON, and the
 * same as Chrome policy on managed Windows (registry) and macOS (profiles) for
 * machines outside Workspace. Optional: Foundation as home and startup page.
 */
function writePolicies(id, foundation) {
  const dir = join(dist, "policy");
  mkdirSync(dir, { recursive: true });
  const today = `${foundation}/#/today`;
  const forceinstall = `${id};https://clients2.google.com/service/update2/crx`;
  writeFileSync(join(dir, "admin-console-policy.json"), JSON.stringify({ foundationUrl: { Value: foundation } }, null, 2) + "\n");
  writeFileSync(
    join(dir, "windows.reg"),
    [
      "Windows Registry Editor Version 5.00",
      "",
      "; Foundation for Chrome: installed for everyone, pointed at the company's Foundation",
      "[HKEY_LOCAL_MACHINE\\SOFTWARE\\Policies\\Google\\Chrome\\ExtensionInstallForcelist]",
      `"1"="${forceinstall}"`,
      "",
      `[HKEY_LOCAL_MACHINE\\SOFTWARE\\Policies\\Google\\Chrome\\3rdparty\\extensions\\${id}\\policy]`,
      `"foundationUrl"="${foundation}"`,
      "",
      "; optional: Today as the home page and the page Chrome opens with",
      "[HKEY_LOCAL_MACHINE\\SOFTWARE\\Policies\\Google\\Chrome]",
      `"HomepageLocation"="${today}"`,
      '"HomepageIsNewTabPage"=dword:00000000',
      '"ShowHomeButton"=dword:00000001',
      '"RestoreOnStartup"=dword:00000004',
      "",
      "[HKEY_LOCAL_MACHINE\\SOFTWARE\\Policies\\Google\\Chrome\\RestoreOnStartupURLs]",
      `"1"="${today}"`,
      "",
    ].join("\r\n"),
  );
  const plist = (domain, body) => `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- ${domain}: deliver as a managed preferences payload (your MDM's custom settings / a configuration profile) -->
<plist version="1.0">
<dict>
${body}
</dict>
</plist>
`;
  writeFileSync(
    join(dir, "com.google.Chrome.plist"),
    plist(
      "com.google.Chrome",
      `  <key>ExtensionInstallForcelist</key>
  <array>
    <string>${forceinstall}</string>
  </array>
  <!-- optional: Today as the home page and the page Chrome opens with -->
  <key>HomepageLocation</key>
  <string>${today}</string>
  <key>HomepageIsNewTabPage</key>
  <false/>
  <key>ShowHomeButton</key>
  <true/>
  <key>RestoreOnStartup</key>
  <integer>4</integer>
  <key>RestoreOnStartupURLs</key>
  <array>
    <string>${today}</string>
  </array>`,
    ),
  );
  writeFileSync(
    join(dir, `com.google.Chrome.extensions.${id}.plist`),
    plist(
      `com.google.Chrome.extensions.${id}`,
      `  <key>foundationUrl</key>
  <string>${foundation}</string>`,
    ),
  );
}

/** a w×w RGBA PNG: paper disc, violet ring, anti-aliased; pad leaves a clear margin (the store icon) */
function icon(w, pad = 0) {
  const paper = [246, 243, 236];
  const violet = [107, 91, 214];
  const px = Buffer.alloc((w * 4 + 1) * w);
  const c = (w - 1) / 2;
  const art = w - 2 * pad;
  const R = art / 2;
  const ring = art * 0.3;
  const thick = Math.max(1.4, art * 0.085);
  for (let y = 0; y < w; y++) {
    px[y * (w * 4 + 1)] = 0;
    for (let x = 0; x < w; x++) {
      const d = Math.hypot(x - c, y - c);
      const disc = Math.max(0, Math.min(1, R - d));
      const onRing = Math.max(0, Math.min(1, thick / 2 + 0.5 - Math.abs(d - ring)));
      const col = paper.map((p, i) => Math.round(p + (violet[i] - p) * onRing));
      const o = y * (w * 4 + 1) + 1 + x * 4;
      px[o] = col[0];
      px[o + 1] = col[1];
      px[o + 2] = col[2];
      px[o + 3] = Math.round(255 * disc);
    }
  }
  const chunk = (type, data) => {
    const len = Buffer.alloc(4);
    len.writeUInt32BE(data.length);
    const td = Buffer.concat([Buffer.from(type), data]);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(td) >>> 0);
    return Buffer.concat([len, td, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(w, 4);
  ihdr[8] = 8;
  ihdr[9] = 6;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk("IHDR", ihdr), chunk("IDAT", deflateSync(px)), chunk("IEND", Buffer.alloc(0))]);
}

function crc32(buf) {
  let c = ~0;
  for (const b of buf) {
    c ^= b;
    for (let k = 0; k < 8; k++) c = (c >>> 1) ^ (0xedb88320 & -(c & 1));
  }
  return ~c;
}
